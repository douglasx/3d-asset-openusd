"""Minimal codeless usdGenSchema replacement.

usd-core wheels do not ship usdGenSchema, so this derives the two runtime
files (generatedSchema.usda, plugInfo.json) from schema/marine/schema.usda.
It only handles what this project uses: single-apply API schemas with
attributes and relationships.

    python -m marinekit.schema_gen
"""
from __future__ import annotations

import json
from pathlib import Path

from pxr import Sdf

SCHEMA_DIR = Path(__file__).resolve().parent.parent / "schema" / "marine"


def generate(schema_dir: Path = SCHEMA_DIR) -> None:
    src = Sdf.Layer.FindOrOpen(str(schema_dir / "schema.usda"))
    glob = src.GetPrimAtPath("/GLOBAL")
    lib = dict(glob.customData) if glob else {}
    lib_name = lib.get("libraryName", "marine")
    prefix = lib_name[:1].upper() + lib_name[1:]

    out = Sdf.Layer.CreateAnonymous(".usda")
    out.comment = "WARNING: THIS FILE IS GENERATED BY marinekit.schema_gen. DO NOT EDIT."
    types = {}
    for spec in src.rootPrims:
        if spec.name == "GLOBAL" or spec.specifier != Sdf.SpecifierClass:
            continue
        cls = Sdf.PrimSpec(out, spec.name, Sdf.SpecifierClass)
        if spec.documentation:
            cls.documentation = spec.documentation
        for prop in spec.properties:
            if isinstance(prop, Sdf.AttributeSpec):
                a = Sdf.AttributeSpec(cls, prop.name, prop.typeName, Sdf.VariabilityVarying)
                if prop.HasDefaultValue():
                    a.default = prop.default
                if prop.documentation:
                    a.documentation = prop.documentation
                if prop.allowedTokens:
                    a.allowedTokens = prop.allowedTokens
            else:
                r = Sdf.RelationshipSpec(cls, prop.name, custom=False)
                if prop.documentation:
                    r.documentation = prop.documentation
        api_type = dict(spec.customData).get("apiSchemaType", "singleApply")
        kind = {"singleApply": "singleApplyAPI", "multipleApply": "multipleApplyAPI"}[api_type]
        types[f"{prefix}{spec.name}"] = {
            "alias": {"UsdSchemaBase": spec.name},
            "autoGenerated": True,
            "bases": ["UsdAPISchemaBase"],
            "schemaKind": kind,
        }

    (schema_dir / "generatedSchema.usda").write_text(out.ExportToString())
    plug = {
        "Plugins": [
            {
                "Info": {"Types": types},
                "LibraryPath": "",
                "Name": lib_name,
                "ResourcePath": ".",
                "Root": ".",
                "Type": "resource",
            }
        ]
    }
    (schema_dir / "plugInfo.json").write_text(json.dumps(plug, indent=2, sort_keys=True) + "\n")


if __name__ == "__main__":
    generate()
    print(f"wrote {SCHEMA_DIR / 'generatedSchema.usda'} and plugInfo.json")
